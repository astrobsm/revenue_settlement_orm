// Flutterwave
// ---------------------------------------------------------------------------
// Amounts in NAIRA. The conversion to kobo happens here and ONLY here.

const FLUTTERWAVE_BASE = 'https://api.flutterwave.com/v3';

export class FlutterwaveAdapter implements PaymentProviderAdapter {
  readonly code = 'FLUTTERWAVE' as const;
  readonly supportsNativeSplit = true;

  private get secret(): string {
    return process.env.FLUTTERWAVE_SECRET_KEY ?? '';
  }

  isConfigured(): boolean {
    return this.secret.length > 0;
  }

  private headers(): Record<string, string> {
    if (!this.isConfigured()) {
      throw new ProviderError('NOT_CONFIGURED', 'Flutterwave is not configured. Set FLUTTERWAVE_SECRET_KEY.');
    }
    return { Authorization: `Bearer ${this.secret}`, 'Content-Type': 'application/json' };
  }

  async initiate(request: InitiateRequest): Promise<InitiateResult> {
    const { status, body } = await providerFetch(`${FLUTTERWAVE_BASE}/payments`, {
      method: 'POST',
      headers: this.headers(),
      body: JSON.stringify({
        tx_ref: request.reference,
        // Kobo out to naira. Exact: kobo are integers, and dividing by 100 for
        // transmission cannot lose precision at these magnitudes. The figure
        // that is later BELIEVED comes back through verify() and is converted
        // back with a round, so the round trip is closed.
        amount: request.amount / 100,
        currency: request.currency,
        redirect_url: request.callbackUrl,
        customer: { email: request.email },
        meta: request.metadata,
      }),
    });

    const data = (body.data ?? {}) as Record<string, unknown>;
    if (status >= 400 || body.status !== 'success' || !data.link) {
      throw new ProviderError('INITIATE_FAILED', String(body.message ?? 'Flutterwave would not start this transaction.'), status);
    }

    return { authorizationUrl: String(data.link), providerReference: request.reference, raw: body };
  }

  async verify(reference: string): Promise<VerifyResult> {
    const { status, body } = await providerFetch(
      `${FLUTTERWAVE_BASE}/transactions/verify_by_reference?tx_ref=${encodeURIComponent(reference)}`,
      { method: 'GET', headers: this.headers() }
    );

    if (status >= 400 || body.status !== 'success') {
      throw new ProviderError('VERIFY_FAILED', String(body.message ?? 'Flutterwave could not verify this transaction.'), status);
    }

    const data = (body.data ?? {}) as Record<string, unknown>;
    const major = data.amount;
    if (typeof major !== 'number' || !Number.isFinite(major)) {
      throw new ProviderError('BAD_AMOUNT', `Flutterwave returned an amount of ${String(major)}.`);
    }

    return {
      // Naira to kobo, rounded once, here.
      amount: Math.round(major * 100),
      currency: String(data.currency ?? 'NGN'),
      status: String(data.status ?? 'unknown'),
      providerTransactionId: data.id != null ? String(data.id) : null,
      paidAt: data.created_at ? new Date(String(data.created_at)) : null,
      raw: body,
    };
  }

  verifySignature(params: { rawBody: string; headers: Headers }): SignatureVerdict {
    return verifyFlutterwaveSignature({
      signatureHeader: params.headers.get('verif-hash'),
      webhookHash: process.env.FLUTTERWAVE_WEBHOOK_HASH ?? '',
    });
  }

  parseEvent(payload: unknown): NormalisedEvent {
    // eslint-disable-next-line @typescript-eslint/no-var-requires
    const { normaliseEvent } = require('./webhooks') as typeof import('./webhooks');
    return normaliseEvent('FLUTTERWAVE', payload);
  }
}

// ---------------------------------------------------------------------------
// The registry
// ---------------------------------------------------------------------------

const ADAPTERS: Record<string, PaymentProviderAdapter> = {
  PAYSTACK: new PaystackAdapter(),
  FLUTTERWAVE: new FlutterwaveAdapter(),
};

/**
 * The adapter for a provider code, or null.
 *
 * Returns null rather than throwing for an unknown code, because the commonest
 * caller is a webhook route handling a URL somebody on the internet chose, and
 * an unknown provider there is a 404 rather than a crash.
 */
export function adapterFor(code: string): PaymentProviderAdapter | null {
  return ADAPTERS[code.toUpperCase()] ?? null;
}

/** Which gateways are actually usable right now. For the settings screen. */
export function configuredProviders(): { code: string; configured: boolean; supportsNativeSplit: boolean }[] {
  return Object.values(ADAPTERS).map((a) => ({
    code: a.code,
    configured: a.isConfigured(),
    supportsNativeSplit: a.supportsNativeSplit,
  }));
}
